#!/usr/bin/env python3
"""gen_hud_place_ids.py - 把地图图标 ID 按"地点类型"归组，写成 C 查表.

为什么需要：大地图上的"地点"其实是 64 个资源 ID、38 种类型（营地/监狱/银行/
机场/矿场/村镇/地标/车队/集结点…），一把开关管不了。类型信息只在资源名里：

    0x002E84154764   UI_Map_Icon_Airport_MapDesc     -> 据点
    0x004A75729881   UI_Icon_VillageLarge_0BEF...    -> 村镇
    0x003E48BC0828   UI_Icon_Landmark_36CB...        -> 地标

所以这张表在构建时由名字生成：hud_icon_ids.h（已由 forge 清单生成）→ 去掉 GUID
后缀取类型 → 按类型归组 → 按 ID 排序写成头文件。运行时只做二分查找，不解析字符串。

分组（顺序必须和 MoreHudControl.c 的 PLG_* 一致，头文件带 HC_PLACE_GROUP_COUNT，
插件用编译期断言对住它）：

    0 据点        营地/训练营/监狱/银行/食品厂/商店/总部/科卡设施/矿场/能源/
                  工业/农业/娱乐/机场/简易机场
    1 村镇与反抗军 大中小村镇、反抗军藏身处
    2 地标与废墟   地标、废墟、残骸、列车、天线
    3 任务与活动点 车队、集结点、HVT、爆炸物、地雷、迫击炮、炮塔、检查站、
                  前哨、未知
    4 奖励与掉落   勋章、技能点、武器掉落、附件掉落、五种活动奖励（kind 26）

用法：
    python tools/gen_hud_place_ids.py            # 写 plugins/MoreHudControl/hud_place_types.h
    python tools/gen_hud_place_ids.py --list     # 只打印每组多少条

游戏更新换了贴图名时，先跑 gen_hud_icon_ids.py，再跑本脚本；出现"未归组的类型"
会直接报错，不会静默丢掉。
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ICON_H = os.path.join(ROOT, "plugins", "MoreHudControl", "hud_icon_ids.h")
OUT_H = os.path.join(ROOT, "plugins", "MoreHudControl", "hud_place_types.h")

GROUPS = ["PLG_HOLD", "PLG_TOWN", "PLG_LAND", "PLG_TASK", "PLG_REWARD"]

# 类型名 -> 组。type 是资源名去掉 UI_[Map_]Icon_ 前缀、_Map/_MapDesc 后缀、
# 以及末尾 GUID 之后剩下的部分，大小写保持原样（这里是精确表）。
TYPE_GROUP = {
    # 0 据点：敌方设施，也是"地图上最想关掉"的一类
    "SBCamp": 0, "SBTrainingCamp": 0, "SBPrison": 0, "SBBank": 0,
    "SBFood": 0, "SBShopping": 0, "SBSantaMuerte": 0,
    "CocaHideout": 0, "CocaShip": 0, "CocaFarming": 0,
    "Mine": 0, "SmallMine": 0, "Energy": 0, "Industry": 0,
    "Farming": 0, "Entertainments": 0, "Airport": 0, "Airfield": 0,
    # 1 村镇与反抗军
    "VillageLarge": 1, "VillageMedium": 1, "VillageSmall": 1, "RebelHideOut": 1,
    # 2 地标与废墟
    "Landmark": 2, "Ruins": 2, "Wreck": 2, "Train": 2, "Antenna": 2,
    # 3 任务与活动点
    "Convoy": 3, "RP": 3, "HVT": 3, "ExplosiveDevice": 3, "Landmine": 3,
    "Mortar": 3, "Turret": 3, "CheckPoint": 3, "Outpost": 3, "Unknown": 3,
    "DLC30_Teammate_Trap": 3,
}

ROW_RE = re.compile(r"\{ (0x[0-9A-Fa-f]+)ULL,\s*(\d+) \},\s*/\* (.*?) \*/")
GUID_RE = re.compile(r"_[0-9A-Fa-f]{8}-[0-9A-Fa-f-]+$")


def type_of(name: str) -> str:
    """UI_Map_Icon_Airport_MapDesc -> Airport（GUID 变体归到同一类型）."""
    s = re.sub(r"_MapDesc$", "", name)
    s = re.sub(r"_Map$", "", s)
    s = re.sub(r"^UI_(?:Map_)?Icon_", "", s, flags=re.I)
    s = GUID_RE.sub("", s)
    return s


def main() -> int:
    if not os.path.exists(ICON_H):
        print("missing %s - run tools/gen_hud_icon_ids.py first" % ICON_H)
        return 1
    text = open(ICON_H, encoding="utf-8", errors="replace").read()
    rows = ROW_RE.findall(text)
    if not rows:
        print("no rows parsed from %s" % ICON_H)
        return 1

    out, unknown, per_group = [], [], [0] * len(GROUPS)
    for hexid, kind, name in rows:
        if kind == "26":
            grp = 4                     # 勋章/技能点/掉落/活动奖励：整类都是奖励
        elif kind == "14":
            t = type_of(name)
            if t not in TYPE_GROUP:
                unknown.append((hexid, name, t))
                continue
            grp = TYPE_GROUP[t]
        else:
            continue
        out.append((int(hexid, 16), grp, name))
        per_group[grp] += 1

    if unknown:
        print("unmapped place type(s) - add them to TYPE_GROUP:")
        for hexid, name, t in unknown:
            print("   %s  %-46s type=%s" % (hexid, name, t))
        return 2

    out.sort(key=lambda r: r[0])
    if "--list" in sys.argv:
        for i, g in enumerate(GROUPS):
            print("%-10s %2d id(s)" % (g, per_group[i]))
        print("total      %2d id(s)" % len(out))
        return 0

    lines = [
        "/* Generated by tools/gen_hud_place_ids.py - do not edit.",
        " *",
        " * 大地图图标 -> 地点分组。由 hud_icon_ids.h 里的资源名生成：名字去掉",
        " * UI_[Map_]Icon_ 前缀、_Map/_MapDesc 后缀和末尾 GUID 就是类型，类型再按",
        " * 语义归到 5 组。运行时按 ID 二分查找，不解析字符串。",
        " *",
        " * 同一类型通常有两条（_Map 与 _MapDesc），GUID 变体是同一类型的另一份",
        " * 资源，因此同一类型可能有三到四条——它们必须一起开关。",
        " *",
        " * 顺序必须和 MoreHudControl.c 的 PLG_* 一致：0 据点 / 1 村镇与反抗军 /",
        " * 2 地标与废墟 / 3 任务与活动点 / 4 奖励与掉落。",
        " */",
        "#ifndef HC_PLACE_TYPES_H",
        "#define HC_PLACE_TYPES_H",
        "",
        "#define HC_PLACE_GROUP_COUNT %d" % len(GROUPS),
        "",
        "typedef struct { unsigned long long id; unsigned char grp; } HcPlaceId;",
        "",
        "/* sorted by id: the plugin looks these up with a binary search */",
        "static const HcPlaceId g_placeIds[] = {",
    ]
    for idv, grp, name in out:
        lines.append("    { 0x%012XULL, %d },   /* %s */" % (idv, grp, name))
    lines += ["};", "", "#endif", ""]
    open(OUT_H, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %s: %d id(s)" % (OUT_H, len(out)))
    for i, g in enumerate(GROUPS):
        print("   %-10s %2d" % (g, per_group[i]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
